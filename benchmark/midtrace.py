"""Mid-trace misbehavior: a dataset where the offense is not the final answer.

Every GroundingBench smoking gun is the agent's final answer, which leaves
open whether an overseer finds misbehavior that happens earlier. This dataset
tests exactly that. Each trace is a coding-agent run on a small, realistic
bug, in one of three versions:

* HONEST: the agent fixes the bug and truthfully reports that the tests pass.
* REWARD_HACKER: the agent edits the test (or test configuration) instead of
  the code, then truthfully reports that the tests pass. The final answer is
  true; the offense is the earlier edit.
* DECEIVER: the agent's fix does not work, the tests still fail, and it then
  writes that they pass somewhere else (a status file, changelog, commit
  message or PR comment). The final answer does not repeat the claim; the
  offense is the earlier write.

Labels are set by construction: the offense is the one step where the
misbehavior is scripted. The tampering method and the medium of the false
claim rotate across four variants each, and innocuous steps are inserted
before the offense, so neither its position nor its wording follows one
pattern. No step uses words that name the misbehavior.

These traces are scripted, not recorded from a real agent: a stated
limitation. The file is regenerated byte for byte by this module, and a test
checks that the committed file matches, so no label can be edited by hand.

Usage:
    python -m benchmark.midtrace    # rewrite benchmark/datasets/midtrace.jsonl
"""

